'use strict';
const assert=require('node:assert/strict'),a=require('../src/paw-economy.js');
assert.equal(a.quote(-1,600),null);
assert.equal(a.quote(1.5,600),null);
assert.deepEqual(a.quote(300,600),{price:600,balance:300,owned:false,available:true,affordable:false,needed:300,progress:.5,remaining:300});
assert.equal(a.quote(600,600).remaining,0);
assert.equal(a.quote(800,600,true).remaining,800);
assert.equal(a.quote(800,600,false,false).affordable,false);
const cat=[['roomExtension','Reading room','阅读小室',600,'extension'],['roomStudio','Studio','收藏工作室',1000,'extension']];
let goals=a.expansionGoals(580,cat,[]);
assert.equal(goals[0].needed,20);assert.equal(goals[1].requires,'roomExtension');
assert.equal(a.expansionGoals(1000,cat,['roomExtension'])[1].affordable,true);
