assert.equal(r.activityMax,40);assert.equal(r.possible,70);assert.equal(r.wheelMin,10);
assert.equal(a.rewards(categories,[],[10,20,30],true).possible,52);
assert.equal(a.rewards([...categories,categories[0]],[],[10],false),null);
assert.deepEqual(a.afterOptionalRewards(goals[0],r),{neededNow:20,neededAfterAllAvailable:0,couldAffordToday:true});
assert.equal(a.afterOptionalRewards(goals[1],r).couldAffordToday,false);
assert.equal(JSON.stringify(categories),original);
console.log('Paw Coin quote, eligibility and optional savings checks passed');
